#!/usr/bin/env python3
"""Boot logo -> src/BootLogoRimRidge.h, compressed with PackBits on 16-bit pixels.

The raw 480x480 RGB565 logo took 460 KB of flash; compressed it is ~24 KB. The firmware decodes
it straight into the panel's frame buffer (drawBootLogo() in the generated header, hooked in by
trgb.setLogoDrawer(), patches/TRGBArduinoSupport-logo-drawer.patch).

Input: a PNG (needs Pillow; scaled to 480x480 if necessary), a raw file of 480x480 RGB565
little-endian pixels (.raw/.bin), or a header in the old uncompressed format (array of 0x..
bytes). Every run decodes the result again and compares it with the input.

    python3 Tools/logo_rle.py logo.png -o src/BootLogoRimRidge.h

Stream format: packets until 480*480 pixels are written. Header byte h:
  h & 0x80: run, (h & 0x7F) + 1 pixels (1..128) of the one following color (u16 LE)
  else:     (h + 1) literal pixels (1..128), each u16 LE
"""
import argparse
import re
import struct
import sys

W = H = 480


def load(path):
    if path.endswith('.png'):
        from PIL import Image
        img = Image.open(path).convert('RGB')
        if img.size != (W, H):
            img = img.resize((W, H))
        return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in img.getdata()]
    data = open(path, 'rb').read()
    if path.endswith('.h'):
        text = data.decode()
        data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', text[text.index('{'):]))
    if len(data) != W * H * 2:
        sys.exit('%s: %d byte, expected %d' % (path, len(data), W * H * 2))
    return list(struct.unpack('<%dH' % (W * H), data))


def encode(px):
    out = bytearray()
    i, n = 0, len(px)
    while i < n:
        j = i
        while j + 1 < n and px[j + 1] == px[i] and j - i < 127:
            j += 1
        if j > i:					# run of 2..128
            out.append(0x80 | (j - i))
            out += struct.pack('<H', px[i])
            i = j + 1
            continue
        k = i						# literals up to the start of the next run
        while k < n and k - i < 128 and not (k + 1 < n and px[k + 1] == px[k]):
            k += 1
        out.append(k - i - 1)
        out += struct.pack('<%dH' % (k - i), *px[i:k])
        i = k
    return bytes(out)


def decode(data):
    px, p = [], 0
    while p < len(data) and len(px) < W * H:
        h = data[p]
        p += 1
        cnt = (h & 0x7F) + 1
        if h & 0x80:
            px += [data[p] | data[p + 1] << 8] * cnt
            p += 2
        else:
            px += list(struct.unpack_from('<%dH' % cnt, data, p))
            p += 2 * cnt
    return px


HEADER = '''#pragma once
// TRGB-BikeComputer "Rim & Ridge" boot logo, drawn by TRGBSuppport::init() through setLogoDrawer()
// (patches/TRGBArduinoSupport-logo-drawer.patch) straight into the panel's frame buffer.
// 480x480 RGB565 little-endian, compressed with PackBits on 16-bit pixels (%(raw)d -> %(size)d byte).
// Generated by Tools/logo_rle.py -- do not edit; the stream format is described there.
// Originally from claude.ai/artifact/RutufhR3sjX9zit2ppEiAY (Rim & Ridge direction).

#include <stdint.h>
#include <stddef.h>

static const uint8_t bootLogoRimRidgeRle[] = {
%(bytes)s
};

// Decodes the logo into fb (480 * 480 pixels). A truncated stream leaves the rest black.
static inline void drawBootLogo(uint16_t* fb) {
	const uint8_t* p = bootLogoRimRidgeRle;
	const uint8_t* const end = p + sizeof(bootLogoRimRidgeRle);
	uint16_t* out = fb;
	uint16_t* const outEnd = fb + 480 * 480;
	while (p < end && out < outEnd) {
		const uint8_t h = *p++;
		size_t n = (h & 0x7F) + 1;
		if (n > static_cast<size_t>(outEnd - out)) n = outEnd - out;
		if (h & 0x80) {
			if (end - p < 2) break;
			const uint16_t c = p[0] | p[1] << 8;
			p += 2;
			while (n--) *out++ = c;
		} else {
			if (static_cast<size_t>(end - p) < 2 * n) break;
			for (; n; n--, p += 2) *out++ = p[0] | p[1] << 8;
		}
	}
	while (out < outEnd) *out++ = 0;
}
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('input')
    ap.add_argument('-o', '--output', default='src/BootLogoRimRidge.h')
    a = ap.parse_args()
    px = load(a.input)
    rle = encode(px)
    if decode(rle) != px:
        sys.exit('round trip failed')
    lines = [' ' + ' '.join('0x%02x,' % b for b in rle[i:i + 24]) for i in range(0, len(rle), 24)]
    open(a.output, 'w').write(HEADER % {'raw': len(px) * 2, 'size': len(rle), 'bytes': '\n'.join(lines)})
    print('%s: %d -> %d byte' % (a.output, len(px) * 2, len(rle)))


if __name__ == '__main__':
    main()
